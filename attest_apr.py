APR_SCHEMA_VERSION: int = 1
TRUST_ROOT_KEY_BASENAME: str = "attest_root_ed25519"


class AttestError(Exception):
    """Base class for attestation trust-root and pinning-record failures."""


class TrustRootKeyMissingError(AttestError):
    """Trust-root key file is absent; it must be generated by explicit ceremony."""


class AttestationPinningRecordError(AttestError):
    """An Attestation Pinning Record is structurally or cryptographically invalid."""


def _xdg_keys_dir() -> Path:
    base = os.environ.get("XDG_DATA_HOME")
    root = Path(base) if base else Path.home() / ".local" / "share"
    return root / "nous" / "keys"


def trust_root_private_key_path() -> Path:
    return _xdg_keys_dir() / TRUST_ROOT_KEY_BASENAME


def trust_root_public_key_path() -> Path:
    return _xdg_keys_dir() / (TRUST_ROOT_KEY_BASENAME + ".pub")


def public_key_fingerprint(public_key: Ed25519PublicKey) -> str:
    raw = public_key.public_bytes(
        serialization.Encoding.Raw, serialization.PublicFormat.Raw
    )
    return hashlib.sha256(raw).hexdigest()


def load_trust_root_private_key(path: Optional[Path] = None) -> Ed25519PrivateKey:
    target = path if path is not None else trust_root_private_key_path()
    if not target.exists():
        raise TrustRootKeyMissingError(
            f"trust-root private key not found at {target}; generate it "
            f"explicitly via scripts/gen_trust_root.py before signing "
            f"(no auto-generation on import, install, or first run)"
        )
    key = serialization.load_pem_private_key(target.read_bytes(), password=None)
    if not isinstance(key, Ed25519PrivateKey):
        raise AttestError(
            f"trust-root key at {target} is not an Ed25519 private key"
        )
    return key


def load_trust_root_public_key(path: Optional[Path] = None) -> Ed25519PublicKey:
    target = path if path is not None else trust_root_public_key_path()
    if not target.exists():
        raise TrustRootKeyMissingError(
            f"trust-root public key not found at {target}; generate it "
            f"explicitly via scripts/gen_trust_root.py (no auto-generation)"
        )
    key = serialization.load_pem_public_key(target.read_bytes())
    if not isinstance(key, Ed25519PublicKey):
        raise AttestError(
            f"trust-root public key at {target} is not an Ed25519 public key"
        )
    return key


def trust_root_public_key_from_raw_b64(raw_b64: str) -> Ed25519PublicKey:
    raw = base64.b64decode(raw_b64, validate=True)
    return Ed25519PublicKey.from_public_bytes(raw)


class TrustRootSignature(BaseModel):
    model_config = ConfigDict(strict=True, extra="forbid", frozen=True)

    algorithm: Literal["ed25519"]
    public_key_fingerprint: str = Field(min_length=64, max_length=64)
    signature_b64: str = Field(min_length=1)


class AttestationPinningRecord(BaseModel):
    model_config = ConfigDict(strict=True, extra="forbid", frozen=True)

    apr_schema_version: int = Field(default=APR_SCHEMA_VERSION)
    scheme: Literal["pinned_tee_key_v1", "phala_response_sig_v1"]  # __s146_u3_apr_scheme_v1__
    enclave_key_id: str = Field(min_length=1)
    enclave_pubkey: str = Field(min_length=1)
    pubkey_alg: Literal["ed25519", "ecdsa_p256", "ecdsa_secp256k1_keccak"]  # __s146_u3_pubkey_alg_v1__
    measurement: str = Field(min_length=2)
    vendor: str = Field(min_length=1)
    model_id: str = Field(min_length=1)
    tcb_level: str = Field(min_length=1)
    quote_sha256: Optional[str] = Field(default=None)
    verified_by: str = Field(min_length=1)
    verified_at: str = Field(min_length=1)
    is_test: bool
    signature: Optional[TrustRootSignature] = Field(default=None)

    @field_validator("measurement")
    @classmethod
    def _measurement_is_hex(cls, value: str) -> str:
        stripped = value[2:] if value[:2].lower() == "0x" else value
        normalized = stripped.lower()
        if len(normalized) < 2 or len(normalized) % 2 != 0:
            raise ValueError("measurement must be non-empty even-length hex")
        if any(c not in "0123456789abcdef" for c in normalized):
            raise ValueError("measurement must contain only hex digits")
        return normalized

    @field_validator("enclave_pubkey")
    @classmethod
    def _enclave_pubkey_is_b64(cls, value: str) -> str:
        try:
            base64.b64decode(value, validate=True)
        except Exception as exc:
            raise ValueError(f"enclave_pubkey must be valid base64: {exc}") from exc
        return value

    @field_validator("quote_sha256")
    @classmethod
    def _quote_sha256_is_hex(cls, value: Optional[str]) -> Optional[str]:
        if value is None:
            return None
        normalized = value.lower()
        if len(normalized) != 64 or any(
            c not in "0123456789abcdef" for c in normalized
        ):
            raise ValueError("quote_sha256 must be 64-char lowercase hex")
        return normalized

    @field_validator("verified_at")
    @classmethod
    def _verified_at_is_rfc3339(cls, value: str) -> str:
        try:
            datetime.fromisoformat(value.replace("Z", "+00:00"))
        except Exception as exc:
            raise ValueError(f"verified_at must be RFC3339 datetime: {exc}") from exc
        return value

    def canonical_body_bytes(self) -> bytes:
        doc = self.model_dump(exclude={"signature"})
        if doc.get("quote_sha256") is None:
            doc.pop("quote_sha256", None)
        return json.dumps(doc, sort_keys=True, separators=(",", ":")).encode("utf-8")


def sign_apr(
    apr: AttestationPinningRecord, private_key: Ed25519PrivateKey
) -> AttestationPinningRecord:
    body = apr.canonical_body_bytes()
    signature_bytes = private_key.sign(body)
    signature = TrustRootSignature(
        algorithm="ed25519",
        public_key_fingerprint=public_key_fingerprint(private_key.public_key()),
        signature_b64=base64.b64encode(signature_bytes).decode("ascii"),
    )
    fields = apr.model_dump(exclude={"signature"})
    return AttestationPinningRecord(**fields, signature=signature)


def verify_apr(
    apr: AttestationPinningRecord, trust_root_public_key: Ed25519PublicKey
) -> bool:
    if apr.signature is None:
        return False
    if public_key_fingerprint(trust_root_public_key) != apr.signature.public_key_fingerprint:
        return False
    try:
        signature_bytes = base64.b64decode(apr.signature.signature_b64, validate=True)
    except Exception:
        return False
    try:
        trust_root_public_key.verify(signature_bytes, apr.canonical_body_bytes())
    except InvalidSignature:
        return False
    except Exception:
        return False
    return True


