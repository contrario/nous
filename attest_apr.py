class AttestationVerdict(BaseModel):
    model_config = ConfigDict(strict=True, extra="forbid", frozen=True)

    attested: bool
    reason: str


def _enclave_ed25519_public_key(
    apr: AttestationPinningRecord,
) -> Ed25519PublicKey:
    raw = base64.b64decode(apr.enclave_pubkey, validate=True)
    return Ed25519PublicKey.from_public_bytes(raw)


def verify_trace_attestation(
    trace: "TraceEnvelope",
    aprs: list[AttestationPinningRecord],
    trust_root_public_key: Ed25519PublicKey,
    *,
    strict_no_test: bool = False,
) -> AttestationVerdict:
    for apr in aprs:
        if not verify_apr(apr, trust_root_public_key):
            return AttestationVerdict(
                attested=False,
                reason=f"APR signature invalid for enclave_key_id {apr.enclave_key_id!r}",
            )

    apr_by_id: dict[str, AttestationPinningRecord] = {}
    for apr in aprs:
        if apr.enclave_key_id in apr_by_id:
            return AttestationVerdict(
                attested=False,
                reason=f"duplicate APR enclave_key_id {apr.enclave_key_id!r}",
            )
        apr_by_id[apr.enclave_key_id] = apr

    receipts = trace.inference_receipts
    if not receipts:
        return AttestationVerdict(
            attested=False, reason="no inference receipts present"
        )

    token_events = {
        index: event
        for index, event in enumerate(trace.events)
        if event.input_tokens > 0 or event.output_tokens > 0
    }

    seen: set[int] = set()
    for receipt in receipts:
        index = receipt.event_index
        if index not in token_events:
            return AttestationVerdict(
                attested=False,
                reason=f"receipt event_index {index} is not a token-bearing event",
            )
        if index in seen:
            return AttestationVerdict(
                attested=False,
                reason=f"duplicate receipt for event_index {index}",
            )
        seen.add(index)

        apr = apr_by_id.get(receipt.enclave_key_id)
        if apr is None:
            return AttestationVerdict(
                attested=False,
                reason=f"receipt enclave_key_id {receipt.enclave_key_id!r} has no pinned APR",
            )
        if receipt.scheme != apr.scheme:
            return AttestationVerdict(
                attested=False,
                reason=f"scheme mismatch at event_index {index}: receipt {receipt.scheme!r} vs APR {apr.scheme!r}",
            )
        if receipt.measurement != apr.measurement:
            return AttestationVerdict(
                attested=False,
                reason=f"measurement mismatch at event_index {index}",
            )
        if receipt.model_id != apr.model_id:
            return AttestationVerdict(
                attested=False,
                reason=f"model_id mismatch at event_index {index}",
            )
        if receipt.source_sha256 != trace.source_sha256:
            return AttestationVerdict(
                attested=False,
                reason=f"source_sha256 mismatch at event_index {index} (foreign or replayed receipt)",
            )
        if apr.pubkey_alg != "ed25519":
            return AttestationVerdict(
                attested=False,
                reason=f"pubkey_alg {apr.pubkey_alg!r} is not supported by verifier v1",
            )
        try:
            enclave_key = _enclave_ed25519_public_key(apr)
        except Exception:
            return AttestationVerdict(
                attested=False,
                reason=f"enclave_pubkey unparseable for APR {apr.enclave_key_id!r}",
            )
        try:
            signature_bytes = base64.b64decode(receipt.signature, validate=True)
        except Exception:
            return AttestationVerdict(
                attested=False,
                reason=f"receipt signature is not valid base64 at event_index {index}",
            )
        try:
            enclave_key.verify(signature_bytes, receipt.signed_payload_bytes())
        except InvalidSignature:
            return AttestationVerdict(
                attested=False,
                reason=f"receipt signature verify failed at event_index {index}",
            )
        except Exception:
            return AttestationVerdict(
                attested=False,
                reason=f"receipt signature verify error at event_index {index}",
            )

        event = token_events[index]
        if (
            receipt.usage_input_tokens != event.input_tokens
            or receipt.usage_output_tokens != event.output_tokens
        ):
            return AttestationVerdict(
                attested=False,
                reason=f"usage token mismatch at event_index {index}",
            )
        if strict_no_test and apr.is_test:
            return AttestationVerdict(
                attested=False,
                reason=f"APR {apr.enclave_key_id!r} is a test pin (strict attestation required)",
            )

    uncovered = sorted(set(token_events.keys()) - seen)
    if uncovered:
        return AttestationVerdict(
            attested=False,
            reason=f"token-bearing events without receipts: {uncovered}",
        )

    return AttestationVerdict(attested=True, reason="")
