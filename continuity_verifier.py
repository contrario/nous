def emit_continuity_verifier(out_dir: Path) -> Path:
    """Write verify_continuity_offline.py (0644) into out_dir; return its path."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    target = out / _OFFLINE_FILENAME
    data = CONTINUITY_VERIFY_OFFLINE_PY.encode("utf-8")
    fd, tmp = tempfile.mkstemp(dir=str(out), prefix=".cv_", suffix=".tmp")
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(data)
        os.chmod(tmp, 0o644)
        os.replace(tmp, str(target))
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise
    return target
